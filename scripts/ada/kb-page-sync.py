#!/usr/bin/env python3
"""kb-page-sync.py — publish declared docs/kb/*.md files into ada-cms-pages.

The durable half of "sync a finding into the CMS report structure": the
repo stays the authoring surface, this script is the publisher. Register
each page in the ada-cms-automation registry (key = page slug) with
    generator: {kind: command, cmd: scripts/ada/kb-page-sync.py <slug>}
and chaba-cms-regen.timer (hourly on tony-dell) re-publishes whenever the
repo file changed — no manual step.

Writer contract (ssot.apps.cms-reports.yml) is honored: meta is merged
never bare-replaced, a provenance footer satisfies cms-audit R2, and
reports-index is regenerated after any write.

Usage:
  kb-page-sync.py <slug> [slug...]     # sync docs/kb/<slug>.md
  kb-page-sync.py --dry-run <slug>     # preview without writing

Env:
  MDDB_BASE_URL   default http://100.102.134.91:11023/v1
"""
from __future__ import annotations

import argparse
import datetime
import importlib.util
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

REPO = Path(os.environ.get("REPO") or Path(__file__).resolve().parents[2])
sys.path.insert(0, str(REPO / "scripts"))
MDDB = os.environ.get("MDDB_BASE_URL",
                      "http://100.102.134.91:11023/v1").rstrip("/")
COLLECTION = "ada-cms-pages"
WRITTEN_BY = "kb-page-sync.py"
KB_DIR = REPO / "docs" / "kb"
PROV_FOOTER = ("\n\n---\n_generated by kb-page-sync.py from "
               "docs/kb/{slug}.md (chaba repo)_\n")


def _post(path: str, payload: dict, timeout: int = 30):
    req = urllib.request.Request(
        f"{MDDB}/{path}", data=json.dumps(payload).encode(),
        headers={"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=timeout))


def get_page(slug: str) -> dict | None:
    try:
        return _post("get", {"collection": COLLECTION, "key": slug,
                             "lang": "en"})
    except urllib.error.HTTPError as e:
        if e.code in (400, 404):
            return None
        raise


def _first(meta: dict, name: str) -> str:
    v = (meta or {}).get(name)
    if isinstance(v, list):
        return str(v[0]) if v else ""
    return str(v) if v else ""


def page_type(slug: str) -> str:
    try:
        spec = importlib.util.spec_from_file_location(
            "cms_normalize_meta", REPO / "scripts/ada/cms-normalize-meta.py")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod.page_type(slug)
    except Exception:
        return "page"


def doc_title(md: str, slug: str) -> str:
    for line in md.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return slug


def doc_summary(md: str) -> str:
    """First substantive non-heading line, capped at ~160 chars (L0)."""
    for line in md.splitlines():
        s = line.strip(" #*_>-|")
        if s and not s.startswith("!") and len(s) > 30:
            return s[:160]
    return ""


def merged_meta(doc: dict | None, slug: str, title: str, summary: str,
                domain: str, fresh_for: str,
                now: datetime.datetime) -> dict:
    meta = {k: (v if isinstance(v, list) else [str(v)])
            for k, v in ((doc or {}).get("meta") or {}).items()}
    today = now.date().isoformat()
    meta.update({
        "bank": ["cms"], "scope": ["tony"],
        "status": meta.get("status") or ["active"],
        "source": ["api"],
        "written_by": [WRITTEN_BY],
        "subject": [slug], "attribute": [page_type(slug)],
        "valid_from": meta.get("valid_from") or [today],
        "last_verified": [today],
        "updated": [now.isoformat(timespec="seconds")],
        "lang": ["en"], "format": ["markdown"],
        "kind": meta.get("kind") or ["page"],
        "title": meta.get("title") or [title],
        "summary": [summary or title],
        "domain": [domain],
    })
    if fresh_for:
        meta["fresh_for"] = [fresh_for]
    return meta


def sync_one(slug: str, domain: str, fresh_for: str, dry: bool) -> str:
    src = KB_DIR / f"{slug}.md"
    if not src.exists():
        return f"{slug}: SKIP — {src} not found"
    body = src.read_text(encoding="utf-8").rstrip() + \
        PROV_FOOTER.format(slug=slug)
    existing = get_page(slug)
    if existing and (existing.get("contentMd") or "").rstrip() == body:
        return f"{slug}: unchanged"
    now = datetime.datetime.now(datetime.timezone.utc)
    meta = merged_meta(existing, slug, doc_title(body, slug),
                       doc_summary(body), domain, fresh_for, now)
    if dry:
        return (f"{slug}: DRY-RUN would publish {len(body)} chars "
                f"(new={'yes' if not existing else 'no'})")
    _post("add", {"collection": COLLECTION, "key": slug, "lang": "en",
                  "contentMd": body, "meta": meta}, timeout=60)
    return f"{slug}: published ({len(body)} chars)"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("slugs", nargs="+")
    ap.add_argument("--domain", default="docs",
                    help="meta.domain bucket (default: docs)")
    ap.add_argument("--fresh-for", default="7d")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    wrote = False
    for slug in args.slugs:
        res = sync_one(slug, args.domain, args.fresh_for, args.dry_run)
        print(res)
        wrote = wrote or ("published" in res)
    if wrote:
        from lib.cms_index import regen_reports_index
        regen_reports_index(MDDB, written_by=WRITTEN_BY)
        print("reports-index regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""wiki-lesson-redirect-map.py — generate the idc02 caddy-edge 301 map
for retired WP lesson CPT permalinks (card
wiki-education-write-cutover-make-wiki-t-7f2e7d, scope item 3).

boards.surf-thailand.com is fronted by the idc02 caddy-edge (it rewrites
/wp/<path> -> /wp/index.php/<path> internally and 301s the index.php
forms back — ssot.wp-boards.yml). The WP slug is a one-way
lesson-<md5(topic)>, so the slug -> Education:<title> map cannot be
derived on the edge; it is generated here from the door's wiki listing
(/lesson op=list source=wiki rows carry slug + wiki_title — the
post-migration job doc already calls this "the 301 table").

Emits ONE import-able Caddyfile fragment. Install:

    import /home/tony/CascadeProjects/chaba/stacks/idc02/boards-lesson-redirects.caddy

inside the boards.surf-thailand.com site block in
~/.config/caddy/Caddyfile on idc02, then `caddy reload` (quadlet
caddy-edge). The matcher accepts both the clean /wp/lesson/<slug> form
and the internal /wp/index.php/lesson/<slug> form so ordering vs the
site's clean-URL rewrite does not matter. Unmapped slugs fall through
to Education:Index — new wiki-primary lessons join the map on the next
regeneration.

Usage: wiki-lesson-redirect-map.py [--api BASE] [--out PATH] [--print]
"""
import argparse, json, os, sys, urllib.parse, urllib.request
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "board"))
try:
    import dispatch_repos as dr
    API_BASE = dr.board_api_base()
except Exception:
    API_BASE = (os.environ.get("BOARD_API") or os.environ.get("RUNNER_API")
                or "https://idc03.taila0626a.ts.net:10000").rstrip("/")

REPO = Path(__file__).resolve().parent.parent
DEFAULT_OUT = REPO / "stacks" / "idc02" / "boards-lesson-redirects.caddy"
WIKI_BASE = "https://wiki.h3.gizmo-thailand.com/index.php?title="


def door_post(api_base: str, body: dict) -> dict:
    req = urllib.request.Request(
        f"{api_base}/lesson", data=json.dumps(
            {"from": "devin", **body}).encode(),
        headers={"Content-Type": "application/json"})
    return json.loads(urllib.request.urlopen(req, timeout=60).read())


def wiki_url(wiki_title: str) -> str:
    """index.php?title= form — wiki.h3 has no $wgArticlePath short URLs
    (/wiki/<t> 404s, verified 2026-11-07). Spaces -> underscores; ':'
    stays literal for readability."""
    return WIKI_BASE + urllib.parse.quote(
        wiki_title.replace(" ", "_"), safe=":")


def fragment(rows: list, today: str) -> str:
    lines = [
        "# AUTO-GENERATED by scripts/wiki-lesson-redirect-map.py "
        f"{today} — {len(rows)} lessons",
        "# WP lesson CPT permalinks -> wiki Education: (card "
        "wiki-education-write-cutover-",
        "# make-wiki-t-7f2e7d). Regenerate after new lessons land "
        "wiki-primary; install via",
        "# `import` inside the boards.surf-thailand.com site block in "
        "~/.config/caddy/Caddyfile",
        "# on idc02, then `caddy reload`.",
        "#",
        "# slug capture accepts the clean /wp/lesson/<slug> form AND "
        "the internal",
        "# /wp/index.php/lesson/<slug> form — ordering vs the site's "
        "clean-URL rewrite",
        "# does not matter.",
        "@lesson_permalink path_regexp lesson_slug "
        r"^/wp/(index\.php/)?lesson/(?<slug>lesson-[0-9a-f]{12})/?$",
        "map {re.lesson_slug.slug} {lesson_redirect} {",
    ]
    for r in rows:
        lines.append(f"\t{r['slug']} {wiki_url(r['wiki_title'])}")
    lines += [
        f"\tdefault {wiki_url('Education:Index')}",
        "}",
        "redir @lesson_permalink {lesson_redirect} permanent",
        "",
        "# the CPT archive index lands on the generated rollup page",
        "@lesson_archive path /wp/lesson /wp/lesson/ "
        "/wp/index.php/lesson /wp/index.php/lesson/",
        f"redir @lesson_archive {wiki_url('Education:Index')} permanent",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api", default=API_BASE)
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--print", dest="stdout", action="store_true",
                    help="print the fragment instead of writing --out")
    a = ap.parse_args()

    r = door_post(a.api, {"op": "list", "source": "wiki"})
    if r.get("source") != "wiki":
        raise SystemExit(
            "door answered without source=wiki — the running board-api "
            "predates the wiki read path")
    rows = [l for l in (r.get("lessons") or [])
            if str(l.get("slug") or "").startswith("lesson-")
            and str(l.get("wiki_title") or "").startswith("Education:")]
    rows.sort(key=lambda l: l["slug"])
    if not rows:
        raise SystemExit("no lessons in the wiki listing — refusing to "
                         "emit an empty map")
    text = fragment(rows, date.today().isoformat())
    if a.stdout:
        print(text)
        return 0
    out = Path(a.out)
    out.write_text(text)
    print(f"wrote {out} — {len(rows)} lesson redirects + archive index")
    return 0


if __name__ == "__main__":
    sys.exit(main())

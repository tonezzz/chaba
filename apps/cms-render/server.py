app = FastAPI(title="chaba-cms-render", version=VERSION)
env = Environment(
    loader=FileSystemLoader(str(APP_DIR / "templates")),
    autoescape=select_autoescape(["html", "xml"]))

def _render(tpl: str, **ctx) -> HTMLResponse:
    return HTMLResponse(env.get_template(tpl).render(**ctx))


def _rfc822(doc: dict) -> str:
    ts = doc.get("updatedAt") or doc.get("addedAt")
    if ts:
        return email.utils.formatdate(int(ts), usegmt=True)
    upd = meta1(doc.get("meta"), "updated")
    try:
        return email.utils.formatdate(
            dt.datetime.fromisoformat(
                upd.replace("Z", "+00:00")).timestamp(), usegmt=True)
    except Exception:
        return ""


@app.get("/healthz")
def healthz():
    state = {"ok": True, "version": VERSION, "collections": {}}
    for coll in COLLECTIONS:
        try:
            docs = LISTING.docs(coll)
            state["collections"][coll] = len(docs)
        except Exception as e:
            state["collections"][coll] = f"ERR {type(e).__name__}"
            state["ok"] = False
    return JSONResponse(state)


@app.get("/", response_class=HTMLResponse)
def index():
    now = dt.datetime.now(dt.timezone.utc)
    sections = []
    for coll in COLLECTIONS:
        first = True
        for sec, title, srows in group_rows(index_rows(coll, now)):
            shown = srows[:40]
            sections.append({
                "id": f"{sec}-{coll}", "title": title,
                "collection": coll, "ui": COLLECTIONS[coll]["ui"],
                "coll_first": first,
                "count": len(srows), "rows": shown,
                "more": len(srows) - len(shown)})
            first = False
    return _render("index.html", sections=sections, ui=UI["en"],
                   host=SITE_HOST, title="chaba-cms index")


@app.get("/k/{kind}", response_class=HTMLResponse)
def kind_listing(kind: str, c: str = Query(default="")):
    now = dt.datetime.now(dt.timezone.utc)
    colls = [c] if c in COLLECTIONS else list(COLLECTIONS)
    rows = []
    for coll in colls:
        rows += [r for r in index_rows(coll, now) if r["kind"] == kind]
    rows.sort(key=lambda r: (r["updated"], r["updated_ts"]), reverse=True)
    return _render("listing.html", kind=kind, rows=rows[:200],
                   count=len(rows), ui=UI["en"], title=f"{kind} — chaba-cms")


@app.get("/feed/{kind}.xml")
def feed(kind: str):
    now_ts = dt.datetime.now().timestamp()
    hit = FEEDS.get(kind)
    if hit and now_ts - hit[0] < LIST_TTL:
        return Response(hit[1], media_type="application/rss+xml")
    now = dt.datetime.now(dt.timezone.utc)
    items = []
    for coll in ("ada-cms-pages", "ada-cms-pages-kk"):
        for r in index_rows(coll, now):
            if r["kind"] == kind:
                items.append((r, coll))
    items = items[:30]
    xml_items = []
    for r, coll in items:
        doc = get_doc(coll, r["key"], COLLECTIONS[coll]["lang"])
        link = (f"https://{SITE_HOST}/p/{r['slug']}"
                + (f"?c={coll}" if coll != "ada-cms-pages" else ""))
        xml_items.append({
            "title": r["title"], "link": link, "guid": f"{coll}/{r['key']}",
            "description": r["summary"] or r["title"],
            "pubDate": _rfc822(doc or {"meta": {"updated": [r["updated"]]}}),
        })
    xml = env.get_template("feed.xml").render(
        kind=kind, title=f"chaba-cms — {kind}", host=SITE_HOST,
        items=xml_items)
    FEEDS[kind] = (now_ts, xml)
    return Response(xml, media_type="application/rss+xml")


@app.get("/p/{slug:path}", response_class=HTMLResponse)
def page(slug: str, c: str = Query(default=""), lang: str = Query(default="")):
    slug = slug.strip("/")
    coll, key, doc, langs = resolve(slug, coll_hint=c, lang=lang)
    if doc is None:
        raise HTTPException(404, f"no doc for {slug!r}")
    updated = doc.get("updatedAt") or meta1(doc.get("meta"), "updated")
    ck = (coll, key, doc.get("lang"), lang)
    hit = PAGES.get(ck, updated)
    if hit is not None:
        return HTMLResponse(hit)

    meta = doc.get("meta") or {}
    ui_lang = COLLECTIONS[coll]["ui"]
    ui = UI.get(ui_lang, UI["en"])
    kind = detect_kind(doc, coll)
    fmt = meta1(meta, "format")
    if fmt == "json" or kind == "automation":
        try:
            body = json.dumps(json.loads(doc.get("contentMd") or "{}"),
                              indent=2, ensure_ascii=False)
        except Exception:
            body = doc.get("contentMd") or ""
        content = f"<pre class='json'>{html.escape(body)}</pre>"
        has_mermaid = False
    else:
        content, has_mermaid = md_to_html(doc.get("contentMd") or "", coll)
    moved = meta1(meta, "moved_to") or meta1(meta, "superseded_by")
    slug_out = doc_slug(doc)
    ctx = dict(
        ui=ui, ui_lang=ui_lang, title=meta1(meta, "title") or key,
        content=content, kind=kind, collection=coll, slug=slug_out,
        updated=meta1(meta, "updated")[:16], fresh=meta1(meta, "fresh_for"),
        stale=is_stale(doc, dt.datetime.now(dt.timezone.utc)),
        status=meta1(meta, "status") or "active",
        role=meta1(meta, "report_role"), domain=meta1(meta, "domain"),
        generated_by=meta1(meta, "generated_by") or meta1(meta, "written_by"),
        summary=meta1(meta, "summary"), moved=moved, langs=langs,
        cur_lang=doc.get("lang", "en"), has_mermaid=has_mermaid,
        host=SITE_HOST, version=VERSION)
    tpl = f"{kind}.html"
    try:
        env.get_template(tpl)
    except Exception:
        tpl = "page.html"
    html_out = env.get_template(tpl).render(**ctx)
    PAGES.put(ck, updated, html_out)
    return HTMLResponse(html_out)


def main() -> None:
    uvicorn.run(app, host=BIND_HOST, port=PORT, log_level="info")


if __name__ == "__main__":
    main()

# caches


class PageCache:
    """Rendered HTML keyed by doc identity + updatedAt — a doc that has
    not changed serves the cached render; MDDB is still asked for the
    doc itself each request (cheap same-host /get)."""

    def __init__(self, maxsize: int = 512):
        self.maxsize = maxsize
        self._d: OrderedDict[tuple, tuple] = OrderedDict()

    def get(self, k: tuple, updated):
        hit = self._d.get(k)
        if hit and hit[0] == updated:
            self._d.move_to_end(k)
            return hit[1]
        return None

    def put(self, k: tuple, updated, value) -> None:
        self._d[k] = (updated, value)
        self._d.move_to_end(k)
        while len(self._d) > self.maxsize:
            self._d.popitem(last=False)


class ListingCache:
    """Per-collection doc lists — slug resolution, lang variants, index.

    TTL rather than doc-keyed: knowing whether a listing changed requires
    the listing itself."""

    def __init__(self, ttl: float):
        self.ttl = ttl
        self._d: dict[str, tuple[float, list[dict]]] = {}

    def docs(self, collection: str) -> list[dict]:
        ts_docs = self._d.get(collection)
        now = dt.datetime.now().timestamp()
        if ts_docs and now - ts_docs[0] < self.ttl:
            return ts_docs[1]
        docs = list_docs(collection)
        self._d[collection] = (now, docs)
        return docs

    def langs_of(self, collection: str, key: str) -> list[str]:
        return sorted({d.get("lang", "en") for d in self.docs(collection)
                       if d.get("key") == key})

    def slug_map(self, collection: str) -> dict[str, str]:
        out = {}
        for d in self.docs(collection):
            s = doc_slug(d)
            if s and s not in out:
                out[s] = d.get("key", s)
        return out

    def invalidate(self) -> None:
        self._d.clear()


PAGES = PageCache()
LISTING = ListingCache(LIST_TTL)

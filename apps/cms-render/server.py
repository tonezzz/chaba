# MDDB client


def _post(path: str, payload: dict, timeout: float = 30):
    req = urllib.request.Request(
        f"{MDDB}/{path}", data=json.dumps(payload).encode(),
        headers={"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=timeout))


def get_doc(collection: str, key: str, lang: str) -> dict | None:
    try:
        d = _post("get", {"collection": collection, "key": key,
                          "lang": lang})
    except Exception:
        return None
    if isinstance(d, dict) and d.get("key"):
        return d
    return None


def list_docs(collection: str, limit: int = 500) -> list[dict]:
    """Paginated collection scan (ada-cms-pages is already >500)."""
    docs, offset = [], 0
    while True:
        page = _post("search", {"collection": collection, "query": "",
                                "limit": limit, "offset": offset})
        if isinstance(page, dict):
            page = page.get("documents") or page.get("docs") or []
        docs += page
        if len(page) < limit:
            return docs
        offset += limit


# ------------------------------------------------------------------
# meta helpers — every meta value is a list in MDDB


def meta1(meta: dict, name: str, default: str = "") -> str:
    v = (meta or {}).get(name)
    if isinstance(v, list):
        return str(v[0]) if v else default
    return str(v) if v is not None else default


def truthy(v: str) -> bool:
    return str(v).strip().lower() in ("true", "yes", "1")


def doc_slug(doc: dict) -> str:
    return meta1(doc.get("meta"), "slug") or doc.get("key", "")


def is_stale(doc: dict, now: dt.datetime) -> bool:
    meta = doc.get("meta") or {}
    ff, upd = meta1(meta, "fresh_for"), meta1(meta, "updated")
    if not ff or not upd:
        return False
    try:
        secs = int(float(ff[:-1]) * {"h": 3600, "d": 86400, "m": 60}[ff[-1]])
        when = dt.datetime.fromisoformat(upd.replace("Z", "+00:00"))
        return (now - when).total_seconds() > secs
    except Exception:
        return False


def detect_kind(doc: dict, collection: str = "") -> str:
    """Render-kind dispatch — meta.kind + report_role + slug family.

    The family names are the per-kind templates in templates/; `page` is
    the catch-all."""
    meta = doc.get("meta") or {}
    key = doc.get("key") or meta1(meta, "slug")
    role = meta1(meta, "report_role")
    domain = meta1(meta, "domain")
    kind = meta1(meta, "kind")
    if collection == "ada-cms-automation":
        return "automation"
    if collection == "chaba-docs":
        return "doc"
    if key.startswith("place-"):
        return "place-report"
    if key.startswith("trip-") or domain == "travel":
        return "trip"
    if key.startswith("house-rule") or key == "house-rules":
        return "house-rules"
    if key == "media-inbox" or key.startswith("media-"):
        return "media-inbox"
    if "timeline" in key:
        return "timeline"
    if role == "digest" or key.endswith("-digest"):
        return "digest"
    if kind == "report":
        return "report"
    return "page"



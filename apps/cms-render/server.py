#!/usr/bin/env python3
"""apps/cms-render — live HTML surface for the MDDB CMS plane.

Card cmssurface-render-digest (cherry-picked Ghost features, 2026-10-14):
chaba-cms had "store it" (MDDB ada-cms-pages*) but no "show it" — this is
the presentation layer. No Ghost, no editor UI, no new DB: MDDB stays the
store, agents stay primary authors.

Reads LIVE from the CMS plane (fetch-on-request — no rebuild pipeline, no
static mirror, no drift):

  ada-cms-pages        main lane   (EN default UI + content)
  ada-cms-pages-kk     kk lane     (Thai default UI + content)
  chaba-docs           repo docs mirror (kind-less, path-shaped keys)
  ada-cms-automation   automation registry (JSON configs -> code view)

Rendered pages are cached in-memory keyed by (collection, key, lang,
updatedAt) — a page re-renders only when the doc actually changed. The
per-collection listing (needed for the index, slug->key resolution and
lang-variant detection) refreshes on CMS_LIST_TTL_S.

Routes:
  /                    index — pages grouped by nav section (meta-driven)
  /p/{slug-or-id}      one page — kind-dispatched template; ?c=<collection>
                       hint, ?lang=en|th variant pick (toggle when >1 lang)
  /k/{kind}            listing of one render kind (page, report, digest,
                       trip, place-report, timeline, media-inbox, …)
  /feed/{kind}.xml     RSS 2.0 for that kind (newest 30)
  /healthz             liveness + mddb reachability

Page conventions followed: docs/kb/cms-page-standard.md (meta contract,
thumbnail `[![a](t)](u)`, ```` ```media ```` + ```mermaid blocks) and
docs/kb/media-inbox-standard.md. Internal `#/slug` links written for the
CMS PWA are rewritten to `/p/slug` here. Media is LINKED (relay-img /
www asset URLs pass through) — never copied.

Runs on idc03 (same host as mddb-cms :11027); served publicly as
cms.surf-thailand.com via the idc02 caddy edge behind Cloudflare Access —
no app-level auth.

Env:
  MDDB_CMS_URL        CMS plane base (default http://127.0.0.1:11027/v1 —
                      on idc03 mddb-cms is loopback; tailnet fallback
                      http://100.102.134.91:11027/v1)
  CMS_SITE_HOST       public hostname used in feed links
                      (default cms.surf-thailand.com)
  CMS_LIST_TTL_S      listing-cache seconds (default 120)
  CMS_BIND_HOST       listen address (default 100.102.134.91 — idc03
                      tailnet IP so the idc02 edge can proxy; use
                      127.0.0.1 for local dev)
  PORT                listen port (default 8010)
"""

def index_rows(collection: str, now: dt.datetime) -> list[dict]:
    docs = LISTING.docs(collection)
    en_keys = {d.get("key") for d in docs if d.get("lang") == "en"}
    rows, seen_keys = [], set()
    for d in docs:
        meta = d.get("meta") or {}
        key = d.get("key", "")
        # one row per key — prefer en, else first lang seen
        if key in seen_keys:
            continue
        if d.get("lang") == "th" and key in en_keys:
            continue
        seen_keys.add(key)
        kind = meta1(meta, "kind")
        status = meta1(meta, "status") or "active"
        if kind == "archive" or status in EXCLUDED_STATUS:
            continue
        if collection in ("ada-cms-pages", "ada-cms-pages-kk") \
                and kind not in ("report", "page"):
            continue
        slug = doc_slug(d)
        role = meta1(meta, "report_role")
        domain = meta1(meta, "domain") or "-"
        if collection == "ada-cms-automation":
            section = "automation"
        elif collection == "chaba-docs":
            section = "docs"
        elif role == "digest":
            section = "digests"
        elif kind == "report":
            section = "reports"
        else:
            section = DOMAIN_SECTION.get(domain, "pages" if domain == "-"
                                         else domain)
        rows.append({
            "slug": slug, "key": key, "collection": collection,
            "title": meta1(meta, "title") or slug,
            "kind": detect_kind(d, collection),
            "section": section,
            "summary": meta1(meta, "summary"),
            "updated": meta1(meta, "updated")[:16],
            "updated_ts": d.get("updatedAt") or 0,
            "fresh": meta1(meta, "fresh_for"),
            "stale": is_stale(d, now),
            "langs": LISTING.langs_of(collection, key),
        })
    rows.sort(key=lambda r: (r["updated"], r["updated_ts"]), reverse=True)
    return rows


def group_rows(rows: list[dict]) -> list[tuple[str, str, list[dict]]]:
    groups: dict[str, list[dict]] = {}
    for r in rows:
        groups.setdefault(r["section"], []).append(r)
    out = []
    for sec in PAGE_ORDER:
        if sec in groups:
            out.append((sec, SECTION_TITLES[sec], groups.pop(sec)))
    for sec in sorted(groups):
        out.append((sec, sec.replace("-", " ").title(), groups[sec]))
    return out



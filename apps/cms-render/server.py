def resolve(slug: str, coll_hint: str = "", lang: str = ""):
    """-> (collection, key, doc, langs) or (None,)*4.

    slug-or-id: try the value as a doc key first (covers chaba-docs
    path-keys), then the collection's meta.slug map."""
    order = list(COLLECTIONS)
    if coll_hint in COLLECTIONS:
        order = [coll_hint] + [c for c in order if c != coll_hint]
    for coll in order:
        want = lang or COLLECTIONS[coll]["lang"]
        doc = get_doc(coll, slug, want)
        if doc is None and lang:
            doc = get_doc(coll, slug, COLLECTIONS[coll]["lang"])
        if doc is None:
            for l in LISTING.langs_of(coll, slug):
                doc = get_doc(coll, slug, l)
                if doc:
                    break
        if doc is None:
            key = LISTING.slug_map(coll).get(slug)
            if key and key != slug:
                doc = get_doc(coll, key, want)
        if doc is not None:
            langs = LISTING.langs_of(coll, doc["key"])
            return coll, doc["key"], doc, langs
    return None, None, None, None


# ------------------------------------------------------------------
# markdown -> html


_FENCE_RE = re.compile(r"^```(mermaid|media)\s*$")
_SENTINEL = "CMSRENDERBLOCK%d"


def _media_block(body: str) -> str:
    """```media {json} -> inline video/audio player (linked, not copied)."""
    try:
        spec = json.loads(body.strip())
    except Exception:
        spec = {}
        for m in re.finditer(r"(\w+)\s*[:=]\s*([^,\s}]+)", body):
            spec[m.group(1)] = m.group(2).strip('"')
    url = html.escape(str(spec.get("url") or spec.get("src") or ""))
    typ = str(spec.get("type") or "video")
    cap = html.escape(str(spec.get("caption") or ""))
    if not url:
        return ""
    tag = "audio" if typ == "audio" else "video"
    el = (f'<{tag} controls preload="metadata" src="{url}">'
          f'</{tag}>')
    return f'<figure class="media">{el}' + \
        (f'<figcaption>{cap}</figcaption>' if cap else "") + '</figure>'


def _mermaid_block(body: str) -> str:
    return f'<pre class="mermaid">{html.escape(body)}</pre>'


def md_to_html(md_text: str, collection: str) -> tuple[str, bool]:
    """CMS-markdown -> html. Handles the family blocks the page standard
    defines (```mermaid, ```media) and rewrites PWA `#/slug` links into
    render paths. Returns (html, has_mermaid)."""
    blocks: list[str] = []
    lines, i, src = (md_text or "").splitlines(), 0, []
    while i < len(lines):
        m = _FENCE_RE.match(lines[i].strip())
        if m:
            j = i + 1
            body_lines = []
            while j < len(lines) and not lines[j].strip().startswith("```"):
                body_lines.append(lines[j])
                j += 1
            kind, body = m.group(1), "\n".join(body_lines)
            blocks.append(_mermaid_block(body) if kind == "mermaid"
                          else _media_block(body))
            src.append("")
            src.append(_SENTINEL % (len(blocks) - 1))
            src.append("")
            i = j + 1
            continue
        src.append(lines[i])
        i += 1

    engine = Markdown(extensions=["tables", "fenced_code", "sane_lists",
                                  "attr_list", "toc", "nl2br"])
    out = engine.convert("\n".join(src))
    for n, raw in enumerate(blocks):
        for pat in (f"<p>{_SENTINEL % n}</p>", _SENTINEL % n):
            if pat in out:
                out = out.replace(pat, raw, 1)
                break
    # PWA-style internal links -> render paths. ?c= pins the doc's own
    # collection so same-slug docs in another lane don't hijack the link.
    hint = "" if collection == "ada-cms-pages" else f"?c={collection}"
    out = re.sub(r'href="#/([^"]+)"',
                 lambda m: f'href="/p/{m.group(1)}{hint}"', out)
    has_mermaid = any(b.startswith('<pre class="mermaid"')
                      for b in blocks)
    return out, has_mermaid


